'use strict';
(async()=>{
 const checks=[],check=(passed,name)=>{checks.push({passed:!!passed,name});if(!passed)throw Error(name);};
 const api=NumericPortraits,sys=await api.System.load('../packs/all-options/pack.json',{catalogURL:'../catalogs/numeric-catalog-1.json'});
 const code=sys.defaultAppearance();code.colors.iris=api.rgb('#123456');const original=JSON.stringify(code);
 check(sys.toDataURL(code)===sys.renderer.toDataURL(sys.toLegacy(code)), 'Numeric rendering matches legacy rendering');
 check(sys.toDataURL(api.deserialize(sys.catalog,api.serialize(sys.catalog,code)))===sys.toDataURL(code),'Numeric save restores exact PNG');
 sys.backgroundProvider=({context})=>context.jobId===101?'#ffffff':'#000000';
 check(sys.toDataURL(code,{context:{jobId:101}})!==sys.toDataURL(code,{context:{jobId:102}}),'Game jobs change background');
 check(JSON.stringify(code)===original,'Job backdrop leaves appearance unchanged');
 check(sys.render(code,{background:null}).getContext('2d').getImageData(0,0,1,1).data[3]===0,'Null background is transparent');
 const background=document.createElement('canvas');background.width=64;background.height=16;background.getContext('2d').fillRect(0,0,64,16);
 check(sys.render(code,{background}).getContext('2d').getImageData(0,0,1,1).data[3]===255,'Image backdrop covers canvas');
 const mount=document.getElementById('wizard');const wizard=PortraitWizard.mount(mount,sys,code);
 const tab=name=>Array.from(mount.querySelectorAll('[role=tab]')).find(b=>b.textContent===name).click();
 const button=name=>Array.from(mount.querySelectorAll('button')).find(b=>b.textContent===name).click();
 check(mount.querySelectorAll('[role=tab]').length===5,'Five guided tabs');
 check(mount.querySelector('input[aria-label="Eyes color"]')?.closest('.wizard-part').querySelector('select').getAttribute('aria-label')===sys.pack.slots.eyes.label,'Iris colour beside eyes');
 tab('Hair');const before=wizard.getAppearance(),select=mount.querySelector('select');
 select.value='102';select.dispatchEvent(new Event('change'));
 check(wizard.getAppearance().parts.hair===102,'Wizard selections use numeric IDs');
 check(wizard.getAppearance().colors.iris===before.colors.iris,'Hair edit preserves eye colour');
 button('Undo');check(wizard.getAppearance().parts.hair===before.parts.hair,'Undo restores previous selection');
 tab('Clothing');button('Randomize this tab');const after=wizard.getAppearance();
 check(Object.keys(after.parts).every(k=>k==='outfit'||after.parts[k]===before.parts[k]),'Tab randomization preserves other parts');
 tab('Review');check(!mount.textContent.includes('1193046'),'Review presents labels');
 wizard.destroy();
 document.getElementById('results').textContent=JSON.stringify(checks,null,2);
 document.body.dataset.result=checks.every(c=>c.passed)?'passed':'failed';
})().catch(e=>{document.getElementById('results').textContent+='\nFAIL: '+e.stack;document.body.dataset.result='failed';});
